import AppKit
import ApplicationServices

struct ClipItem: Identifiable {
    let id = UUID()
    let text: String
    let preview: String

    init(_ text: String) {
        self.text = text
        // Однострочное превью: первая непустая строка, пробелы схлопнуты.
        let first = text.split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .first { !$0.isEmpty } ?? ""
        let collapsed = first.split(whereSeparator: { $0 == " " || $0 == "\t" }).joined(separator: " ")
        self.preview = String(collapsed.prefix(120))
    }
}

/// История буфера обмена: последние 10 текстовых копирований.
///
/// У NSPasteboard нет уведомления об изменении, поэтому это единственное место в приложении с таймером:
/// раз в ~1 с сравнивается целое `changeCount` (читать содержимое начинаем, только если оно изменилось).
///
/// Приватность: история живёт только в памяти (на диск не пишется), записи, помеченные менеджерами паролей как
/// скрытые/временные (`org.nspasteboard.*`), пропускаются; при отключении модуля история стирается.
final class ClipboardManager: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    static let limit = 10
    private static let maxChars = 20_000
    private static let secret: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var internalUntil = Date.distantPast

    func start() {
        guard timer == nil else { return }
        lastCount = NSPasteboard.general.changeCount     // то, что было в буфере до включения, не записываем
        let t = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in self?.check() }
        t.tolerance = 0.5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        items.removeAll()
    }

    func clear() { items.removeAll() }

    /// Приложение временно меняет буфер (⌘C для переводчика) — эти изменения в историю не пишем.
    func beginInternalChange() { internalUntil = Date().addingTimeInterval(3) }
    func endInternalChange() {
        lastCount = NSPasteboard.general.changeCount
        internalUntil = Date().addingTimeInterval(0.3)
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        if Date() < internalUntil { return }              // временные записи самого приложения (переводчик)

        let types = pb.types ?? []
        if types.contains(where: { Self.secret.contains($0.rawValue) }) { return }
        guard let s = pb.string(forType: .string),
              !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        push(String(s.prefix(Self.maxChars)))
    }

    private func push(_ text: String) {
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Возвращает запись в буфер (и наверх списка). При `autoPaste` ещё и вставляет в активное приложение.
    func restore(_ item: ClipItem, autoPaste: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastCount = pb.changeCount                       // собственную запись заново не обрабатываем
        push(item.text)

        guard autoPaste, AXIsProcessTrusted() else { return }
        // Панель острова не активируется, поэтому активным остаётся приложение, в которое пользователь печатал.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) { Self.pressCommandV() }
    }

    /// Просит у системы доступ «Универсальный доступ» (нужен только для автовставки).
    static func requestAccessibility() {
        Accessibility.prompt()
    }

    private static func pressCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)   // 9 = «V»
        let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
